import { useEffect, useRef } from 'react'
import Icon from '../../components/Icon.jsx'
import { amountInWordsINR, formatDate, formatINR } from '../../utils/format.js'

/**
 * Printable receipt for a verified customer payment. Marked DEMO: the prototype has no
 * company letterhead, signatory or legal receipt numbering, so this is not a valid receipt.
 */
export default function ReceiptVoucher({ receipt, account, bankAccountName, onClose }) {
  const closeRef = useRef(null)
  useEffect(() => {
    closeRef.current?.focus()
    const onKey = (e) => e.key === 'Escape' && (e.stopPropagation(), onClose())
    document.addEventListener('keydown', onKey, true)
    return () => document.removeEventListener('keydown', onKey, true)
  }, [onClose])

  return (
    <div className="voucher-scrim" onClick={(e) => { e.stopPropagation(); onClose() }}>
      <div className="voucher-dialog" role="dialog" aria-modal="true" aria-labelledby="voucher-title" onClick={(e) => e.stopPropagation()}>
        <div className="voucher-actions no-print">
          <button className="btn btn-primary" onClick={() => window.print()}><Icon name="download" />Print / save as PDF</button>
          <button ref={closeRef} className="btn" onClick={onClose}>Close</button>
        </div>

        <article className="voucher" aria-label={`Receipt ${receipt.receiptNo}`}>
          <div className="voucher-watermark" aria-hidden="true">DEMO</div>
          <header className="voucher-head">
            <div>
              <div className="voucher-company">BuildDesk Demo Builders</div>
              <div className="cell-sub">Prototype company · address and GSTIN not configured</div>
            </div>
            <div className="voucher-no">
              <div id="voucher-title" className="voucher-title">Payment Receipt</div>
              <div>No. <b>{receipt.receiptNo}</b></div>
              <div>Date {formatDate(receipt.verifiedOn || receipt.date)}</div>
            </div>
          </header>

          <p className="voucher-line">
            Received with thanks from <b>{account.customer}</b> the sum of <b>{formatINR(receipt.amount)}</b>
            {' '}({amountInWordsINR(receipt.amount)}) towards {account.unitType.toLowerCase()} <b>{account.unit}</b>, {account.projectName}.
          </p>

          <dl className="voucher-grid">
            <dt>Customer</dt><dd>{account.customer}</dd>
            <dt>Project / unit</dt><dd>{account.projectName} · {account.unitType} {account.unit}</dd>
            <dt>Booking</dt><dd>{account.bookingId}</dd>
            <dt>Amount</dt><dd><b>{formatINR(receipt.amount)}</b></dd>
            <dt>Payment date</dt><dd>{formatDate(receipt.date)}</dd>
            <dt>Payment method</dt><dd>{receipt.method}</dd>
            <dt>Reference</dt><dd>{receipt.reference || '-'}</dd>
            <dt>Credited to</dt><dd>{bankAccountName || '-'}</dd>
            {receipt.against && <><dt>Towards</dt><dd>{receipt.against}</dd></>}
            <dt>Bank verification</dt><dd>{receipt.bankStatus || 'Verified'}{receipt.verifiedBy ? ` · ${receipt.verifiedBy}` : ''}</dd>
          </dl>

          <footer className="voucher-foot">
            <span>Balance after this receipt: <b>{formatINR(account.balance)}</b></span>
            <span className="voucher-sign">Authorised signatory</span>
          </footer>
          <p className="voucher-demo">
            DEMO RECEIPT generated by a prototype. Not valid for any payment, tax or legal purpose.
          </p>
        </article>
      </div>
    </div>
  )
}
